# 6. “Периметр прямокутника”
# Користувач вводить довжину і ширину. Програма виводить периметр.
# Приклад:
# Введіть довжину: 5
# Введіть ширину: 3
# Периметр: 16

length = int(input("Введіть довжину: "))
width = int(input("Введіть ширину: "))
perimeter = 2 * (length + width)
print("Периметр:", perimeter)