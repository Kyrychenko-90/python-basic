# 4. “Розрахунок знижки”
# Користувач вводить ціну товару і розмір знижки у %.
# Програма виводить кінцеву ціну.
# Приклад:
# Введіть ціну: 1000
# Введіть знижку (%): 15
# Ціна зі знижкою: 850.0

price = float(input("Введіть ціну: "))
discount = float(input("Введіть знижку (%): "))
final_price = round(price * (100 - discount) / 100, 2)
print("Ціна зі знижкою:", final_price)