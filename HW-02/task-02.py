# 2. “Середнє трьох чисел”
# Програма запитує три числа і виводить їх середнє арифметичне.
# Приклад:
# Введіть три числа: 2, 4, 6
# Середнє: 4.0

your_number_1 = int(input("Введіть перше число: "))
your_number_2 = int(input("Введіть друге число: "))
your_number_3 = int(input("Введіть третє число: "))
print("Середнє:", (your_number_1 + your_number_2 + your_number_3) / 3)

